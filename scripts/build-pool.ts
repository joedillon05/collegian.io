/**
 * Validate data/curation.csv against the schools list and emit
 * src/data/athletes.generated.ts, the pool the game ships with.
 *
 *   npm run build:pool
 *
 * Fails loudly on any bad row so a typo never reaches players.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { SCHOOL_BY_ID } from "../src/data/schools.ts";

const SRC = new URL("../data/curation.csv", import.meta.url);
const OUT = new URL("../src/data/athletes.generated.ts", import.meta.url);

const COLUMNS = ["id", "name", "sport", "league", "number", "active", "gender", "tier", "schools", "source", "verified"] as const;
type Col = (typeof COLUMNS)[number];

function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((f) => f.trim() !== "")) rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== "" || row.length) { row.push(field); if (row.some((f) => f.trim() !== "")) rows.push(row); }
  return rows;
}

const text = readFileSync(SRC, "utf8");
const [header, ...lines] = parseCsv(text);
if (header.join(",") !== COLUMNS.join(",")) {
  throw new Error(`curation.csv header must be: ${COLUMNS.join(",")}`);
}

const errors: string[] = [];
const ids = new Set<string>();
const names = new Set<string>();
const out: string[] = [];
const perTier: Record<string, number> = {};

lines.forEach((cells, n) => {
  const line = n + 2;
  const r = Object.fromEntries(COLUMNS.map((c, i) => [c, (cells[i] ?? "").trim()])) as Record<Col, string>;
  const bad = (msg: string) => errors.push(`line ${line} (${r.id || r.name || "?"}): ${msg}`);

  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(r.id)) bad("id must be a lowercase slug");
  if (ids.has(r.id)) bad("duplicate id");
  ids.add(r.id);
  if (!r.name) bad("missing name");
  if (names.has(r.name.toLowerCase())) bad("duplicate name");
  names.add(r.name.toLowerCase());
  if (!r.sport) bad("missing sport");
  if (!/^(yes|no)$/.test(r.active)) bad("active must be yes or no");
  if (!/^(m|f)$/.test(r.gender)) bad("gender must be m or f");
  if (!/^[1-5]$/.test(r.tier)) bad("tier must be 1-5");
  const schools = r.schools.split(";").map((s) => s.trim()).filter(Boolean);
  if (schools.length === 0) bad("needs at least one school");
  for (const s of schools) if (!SCHOOL_BY_ID.has(s)) bad(`unknown school id "${s}"`);
  if (new Set(schools).size !== schools.length) bad("duplicate school");
  if (!/^(human|claude|)$/.test(r.verified)) bad("verified must be human, claude, or blank");
  if (r.verified === "") return; // unreviewed rows never ship

  perTier[r.tier] = (perTier[r.tier] ?? 0) + 1;
  const num = r.number === "" ? "null" : JSON.stringify(r.number);
  out.push(`  [${JSON.stringify(r.id)}, ${JSON.stringify(r.name)}, ${JSON.stringify(r.sport)}, ${JSON.stringify(r.league)}, ${num}, ${r.active === "yes"}, ${JSON.stringify(r.gender)}, ${r.tier}, ${JSON.stringify(schools)}],`);
});

if (errors.length) {
  console.error(errors.join("\n"));
  console.error(`\n${errors.length} problem(s) in data/curation.csv`);
  process.exit(1);
}

const file = `// GENERATED by scripts/build-pool.ts from data/curation.csv. Do not edit by hand.
import type { Athlete, Gender, Tier } from "@/lib/types";

type Row = [string, string, string, string, string | null, boolean, Gender, Tier, string[]];

const ROWS: Row[] = [
${out.join("\n")}
];

export const ATHLETES: Athlete[] = ROWS.map(([id, name, sport, league, number, active, gender, tier, schools]) => ({
  id, name, sport, league, number, active, gender, tier, schools,
}));

export const ATHLETE_BY_ID: Map<string, Athlete> = new Map(ATHLETES.map((a) => [a.id, a]));
`;
writeFileSync(OUT, file);
const total = Object.values(perTier).reduce((a, b) => a + b, 0);
console.log(`wrote ${total} athletes -> src/data/athletes.generated.ts`);
console.log("per tier:", [1, 2, 3, 4, 5].map((t) => `T${t}=${perTier[t] ?? 0}`).join("  "));
