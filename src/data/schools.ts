function toSchool(row: Row, division?: Division): School {
  const [id, name, fullName, state, aliases = []] = row;
  return { id, name, fullName, state, aliases, ...(division ? { division } : {}) };
}

export const SCHOOLS: School[] = [
  ...D1.map((r) => toSchool(r)),
  ...OTHER.map(([r, d]) => toSchool(r, d)),
];

export const SCHOOL_BY_ID: Map<string, School> = new Map(SCHOOLS.map((s) => [s.id, s]));

export function schoolName(id: string): string {
  return SCHOOL_BY_ID.get(id)?.name ?? id;
}
